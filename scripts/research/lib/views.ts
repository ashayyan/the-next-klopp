// Pure renderers for the generated Markdown views (RSCH-04, RSCH-05). Erasable TypeScript only.
// Every renderer returns the whole file as a string with "\n" line endings and a trailing newline.
// Text that comes from agents or the web is escaped before it lands in a table cell (T-02-09).
import { TRACKS } from "./domains.ts";
import { layers } from "./graph.ts";
import type { Concept, ResearchBundle } from "./research-io.ts";

const PARTS = ["A", "B", "C", "D", "E", "F", "G"] as const;

/** First line of every generated view. The test and `--check` rely on this exact wording. */
export function generatedHeader(inputs: string[]): string {
  return `<!-- Generated by scripts/research/render-views.ts from ${inputs.join(", ")}. Do not edit by hand. -->`;
}

/** Table-cell text: no raw HTML tags, no line breaks, pipes escaped so a cell cannot split a row. */
export function cell(text: string): string {
  return text
    .replace(/<\/?[A-Za-z!][^>]*>/g, "")
    .replace(/[\r\n]+/g, " ")
    .replace(/\s+/g, " ")
    .trim()
    .replace(/\|/g, "\\|");
}

function table(headers: string[], rows: string[][]): string[] {
  const line = (cells: string[]) => `| ${cells.map(cell).join(" | ")} |`;
  return [line(headers), `| ${headers.map(() => "---").join(" | ")} |`, ...rows.map(line)];
}

function list(ids: readonly string[]): string {
  return ids.length > 0 ? ids.join(", ") : "none";
}

function finish(lines: string[]): string {
  return `${lines.join("\n").replace(/\n{3,}/g, "\n\n")}\n`;
}

export function prereqMap(concepts: readonly Concept[]): Map<string, string[]> {
  return new Map(concepts.map((c) => [c.id, [...c.prerequisites]]));
}

function trackTitle(trackId: string): string {
  return TRACKS.find((t) => t.id === trackId)?.title ?? trackId;
}

/** Tracks in TRACKS order, then any track id the map uses that TRACKS does not know. */
function trackOrder(concepts: readonly Concept[]): string[] {
  const known = TRACKS.map((t) => t.id);
  const extra = [...new Set(concepts.map((c) => c.track))].filter((t) => !known.includes(t));
  return [...known, ...extra.sort()];
}

export function renderConceptMap(bundle: ResearchBundle): string {
  const { concepts, edges } = bundle;
  const { layer } = layers(prereqMap(concepts));
  const depth = layer.size > 0 ? Math.max(...layer.values()) + 1 : 0;
  const roots = concepts.filter((c) => c.prerequisites.length === 0).length;
  const prereqEdges = edges.filter((e) => e.kind === "prerequisite").length;
  const otherEdges = edges.length - prereqEdges;

  const lines: string[] = [
    generatedHeader(["concept-map.json"]),
    "",
    "# Concept map",
    "",
    `- Concepts: ${concepts.length}`,
    `- Root concepts (no prerequisites): ${roots}`,
    `- Prerequisite layers: ${depth}`,
    `- Edges: ${prereqEdges} prerequisite, ${otherEdges} related or contrasting`,
    "",
    "## Concepts per Part",
    "",
    ...table(
      ["Part", "Concepts"],
      PARTS.map((p) => [p, String(concepts.filter((c) => c.part === p).length)]),
    ),
  ];

  const tracks = trackOrder(concepts);
  for (const part of PARTS) {
    const inPart = concepts.filter((c) => c.part === part);
    if (inPart.length === 0) continue;
    lines.push("", `## Part ${part}`);
    for (const track of tracks) {
      const rows = inPart
        .filter((c) => c.track === track)
        .sort(
          (a, b) => (layer.get(a.id) ?? 999) - (layer.get(b.id) ?? 999) || a.id.localeCompare(b.id),
        );
      if (rows.length === 0) continue;
      lines.push(
        "",
        `### ${cell(track)}: ${cell(trackTitle(track))}`,
        "",
        ...table(
          ["Id", "Title", "Summary", "Layer", "Prerequisites", "Status", "Sources"],
          rows.map((c) => [
            c.id,
            c.title,
            c.summary,
            layer.has(c.id) ? String(layer.get(c.id)) : "cycle",
            list(c.prerequisites),
            c.status,
            list(c.sources),
          ]),
        ),
      );
    }
  }
  return finish(lines);
}
