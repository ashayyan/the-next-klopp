// Tests for the generated research views: the mini fixture bundle, the pure renderers and the CLI.
import { spawnSync } from "node:child_process";
import { cpSync, existsSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { afterAll, describe, expect, it } from "vitest";
import { THREADS } from "./lib/domains.ts";
import { layers, studyOrder } from "./lib/graph.ts";
import { checkReferences, loadResearchBundle } from "./lib/research-io.ts";
import {
  prereqMap,
  renderConceptMap,
  renderCurriculumDraft,
  renderGaps,
  renderRoleCompetencies,
} from "./lib/views.ts";

const REPO = join(import.meta.dirname, "..", "..");
const MINI = join(import.meta.dirname, "fixtures", "mini");
const CLI = join(import.meta.dirname, "render-views.ts");

const temps: string[] = [];
function tempDir(): string {
  const dir = mkdtempSync(join(tmpdir(), "klopp-views-"));
  temps.push(dir);
  return dir;
}
afterAll(() => {
  for (const dir of temps) rmSync(dir, { recursive: true, force: true });
});

function runCli(args: string[]) {
  return spawnSync(process.execPath, [CLI, ...args], { cwd: REPO, encoding: "utf8" });
}

describe("mini fixture bundle", () => {
  it("loads with no schema violations and consistent references", () => {
    const bundle = loadResearchBundle(MINI);
    expect(bundle.concepts.length).toBeGreaterThanOrEqual(10);
    expect(bundle.sources).toHaveLength(4);
    expect(bundle.config).not.toBeNull();
    expect(checkReferences(bundle)).toEqual([]);
  });

  it("lists missing files without throwing", () => {
    const bundle = loadResearchBundle(join(tempDir(), "nothing"));
    expect(bundle.missing).toContain("concept-map.json");
    expect(bundle.concepts).toEqual([]);
  });

  it("reports every violation of every file in one error", () => {
    const dir = tempDir();
    writeFileSync(
      join(dir, "concept-map.json"),
      JSON.stringify({ schema_version: 1, concepts: [{ id: "x" }], edges: [] }),
    );
    writeFileSync(join(dir, "curriculum-config.json"), JSON.stringify({ schema_version: 2 }));
    let message = "";
    try {
      loadResearchBundle(dir);
    } catch (e) {
      message = (e as Error).message;
    }
    expect(message).toContain("concept-map.json");
    expect(message).toContain("curriculum-config.json");
  });
});

describe("renderConceptMap", () => {
  const bundle = loadResearchBundle(MINI);

  it("is deterministic and names every concept", () => {
    const first = renderConceptMap(bundle);
    expect(renderConceptMap(bundle)).toBe(first);
    for (const c of bundle.concepts) expect(first).toContain(c.id);
    expect(first.startsWith("<!-- Generated by scripts/research/render-views.ts from ")).toBe(true);
    expect(first).toContain("Do not edit by hand. -->");
    expect(first).not.toContain("\r");
  });

  it("escapes pipes and strips raw HTML from agent-written text", () => {
    const first = bundle.concepts[0];
    if (!first) throw new Error("fixture has no concepts");
    const hostile = {
      ...bundle,
      concepts: [{ ...first, title: "a|b <script>x</script>", summary: "line\nbreak" }],
    };
    const md = renderConceptMap(hostile);
    expect(md).toContain("a\\|b x");
    expect(md).not.toContain("<script>");
    expect(md).not.toContain("line\nbreak");
  });
});

describe("render-views CLI", () => {
  it("writes CONCEPT_MAP.md byte-equal to the in-memory render", () => {
    const out = tempDir();
    const res = runCli(["--root", MINI, "--out", out]);
    expect(res.status, res.stderr).toBe(0);
    const written = readFileSync(join(out, "CONCEPT_MAP.md"));
    expect(written.equals(Buffer.from(renderConceptMap(loadResearchBundle(MINI)), "utf8"))).toBe(
      true,
    );
  });

  it("exits 1 when --root has no concept-map.json", () => {
    const res = runCli(["--root", join(MINI, "does-not-exist"), "--check"]);
    expect(res.status).toBe(1);
    expect(res.stderr).toContain("no research inputs under");
  });
});

describe("fixture links are consistent", () => {
  const bundle = loadResearchBundle(MINI);

  it("concept.roles and competency.concepts match what roles and concepts declare", () => {
    for (const c of bundle.concepts) {
      const expected = bundle.roles
        .filter((r) => r.competencies.some((k) => c.competencies.includes(k.id)))
        .map((r) => r.id)
        .sort();
      expect([...c.roles].sort(), c.id).toEqual(expected);
    }
    for (const k of bundle.competencies) {
      const expected = bundle.concepts
        .filter((c) => c.competencies.includes(k.id))
        .map((c) => c.id)
        .sort();
      expect([...k.concepts].sort(), k.id).toEqual(expected);
    }
  });

  it("edges equal the prerequisite pairs plus the related edge", () => {
    const pairs = bundle.concepts.flatMap((c) => c.prerequisites.map((p) => `${p}>${c.id}`)).sort();
    const prereqEdges = bundle.edges
      .filter((e) => e.kind === "prerequisite")
      .map((e) => `${e.from}>${e.to}`)
      .sort();
    expect(prereqEdges).toEqual(pairs);
    expect(bundle.edges.filter((e) => e.kind === "related")).toHaveLength(1);
  });

  it("every thread track has a starter inside the layer bound", () => {
    const config = bundle.config;
    if (!config) throw new Error("fixture config missing");
    const { layer } = layers(prereqMap(bundle.concepts));
    for (const t of THREADS) {
      const starter = config.thread_starters[t.track];
      expect(starter, t.track).toBeDefined();
      expect(layer.get(starter as string) ?? 99).toBeLessThanOrEqual(config.max_starter_layer);
    }
  });
});

describe("renderCurriculumDraft", () => {
  const bundle = loadResearchBundle(MINI);
  const md = renderCurriculumDraft(bundle);

  it("lists stages in study order and states the order follows the concept map", () => {
    const ids = [...md.matchAll(/^\| \d+ \| ([a-z0-9-]+) \|/gm)].map((m) => m[1]);
    const starters = Object.values(bundle.config?.thread_starters ?? {}).filter(
      (x): x is string => x !== undefined,
    );
    expect(ids).toEqual(studyOrder(bundle.concepts, { threadStarters: starters }).order);
    expect(md).toContain("follows the concept map, not track numbers");
  });

  it("marks the thread starters and shows the stage where each thread starts", () => {
    const lines = md.split("\n");
    for (const t of THREADS) {
      expect(
        lines.some((l) => l.startsWith(`| ${t.label} |`)),
        t.label,
      ).toBe(true);
    }
    const watch = lines.find((l) => /^\| \d+ \| watch-one-player \|/.test(l));
    expect(watch).toContain("Watch Gym");
    const roleMap = lines.find((l) => /^\| \d+ \| role-map-intro \|/.test(l));
    expect(roleMap).toContain("Role Map");
    const plain = lines.find((l) => /^\| \d+ \| pitch-markings \|/.test(l));
    expect(plain).not.toContain("Role Map");
  });

  it("is deterministic and starts with the generated header", () => {
    expect(renderCurriculumDraft(bundle)).toBe(md);
    expect(md.startsWith("<!-- Generated by scripts/research/render-views.ts from ")).toBe(true);
  });
});

describe("renderRoleCompetencies", () => {
  const bundle = loadResearchBundle(MINI);
  const md = renderRoleCompetencies(bundle);

  it("has one section per role with the descriptor at the target level and linked concepts", () => {
    for (const r of bundle.roles) expect(md).toContain(`## ${r.title}`);
    const coach = md.slice(md.indexOf("## Head Coach"), md.indexOf("## Sporting Director"));
    expect(coach).toContain("reading-the-game");
    expect(coach).toContain("Reads the game live and adjusts the plan within minutes.");
    expect(coach).not.toContain("Knows the pitch, the lines and the basic shapes");
    expect(coach).toContain("one-line-match-note");
    expect(coach).toContain("game-knowledge");
  });

  it("starts with the generated header", () => {
    expect(md.startsWith("<!-- Generated by scripts/research/render-views.ts from ")).toBe(true);
  });
});

