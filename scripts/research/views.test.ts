// Tests for the generated research views: the mini fixture bundle, the pure renderers and the CLI.
import { spawnSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { afterAll, describe, expect, it } from "vitest";
import { checkReferences, loadResearchBundle } from "./lib/research-io.ts";
import { renderConceptMap } from "./lib/views.ts";

const REPO = join(import.meta.dirname, "..", "..");
const MINI = join(import.meta.dirname, "fixtures", "mini");
const CLI = join(import.meta.dirname, "render-views.ts");

const temps: string[] = [];
function tempDir(): string {
  const dir = mkdtempSync(join(tmpdir(), "klopp-views-"));
  temps.push(dir);
  return dir;
}
afterAll(() => {
  for (const dir of temps) rmSync(dir, { recursive: true, force: true });
});

function runCli(args: string[]) {
  return spawnSync(process.execPath, [CLI, ...args], { cwd: REPO, encoding: "utf8" });
}

describe("mini fixture bundle", () => {
  it("loads with no schema violations and consistent references", () => {
    const bundle = loadResearchBundle(MINI);
    expect(bundle.concepts.length).toBeGreaterThanOrEqual(10);
    expect(bundle.sources).toHaveLength(4);
    expect(bundle.config).not.toBeNull();
    expect(checkReferences(bundle)).toEqual([]);
  });

  it("lists missing files without throwing", () => {
    const bundle = loadResearchBundle(join(tempDir(), "nothing"));
    expect(bundle.missing).toContain("concept-map.json");
    expect(bundle.concepts).toEqual([]);
  });

  it("reports every violation of every file in one error", () => {
    const dir = tempDir();
    writeFileSync(
      join(dir, "concept-map.json"),
      JSON.stringify({ schema_version: 1, concepts: [{ id: "x" }], edges: [] }),
    );
    writeFileSync(join(dir, "curriculum-config.json"), JSON.stringify({ schema_version: 2 }));
    let message = "";
    try {
      loadResearchBundle(dir);
    } catch (e) {
      message = (e as Error).message;
    }
    expect(message).toContain("concept-map.json");
    expect(message).toContain("curriculum-config.json");
  });
});

describe("renderConceptMap", () => {
  const bundle = loadResearchBundle(MINI);

  it("is deterministic and names every concept", () => {
    const first = renderConceptMap(bundle);
    expect(renderConceptMap(bundle)).toBe(first);
    for (const c of bundle.concepts) expect(first).toContain(c.id);
    expect(first.startsWith("<!-- Generated by scripts/research/render-views.ts from ")).toBe(true);
    expect(first).toContain("Do not edit by hand. -->");
    expect(first).not.toContain("\r");
  });

  it("escapes pipes and strips raw HTML from agent-written text", () => {
    const first = bundle.concepts[0];
    if (!first) throw new Error("fixture has no concepts");
    const hostile = {
      ...bundle,
      concepts: [{ ...first, title: "a|b <script>x</script>", summary: "line\nbreak" }],
    };
    const md = renderConceptMap(hostile);
    expect(md).toContain("a\\|b x");
    expect(md).not.toContain("<script>");
    expect(md).not.toContain("line\nbreak");
  });
});

describe("render-views CLI", () => {
  it("writes CONCEPT_MAP.md byte-equal to the in-memory render", () => {
    const out = tempDir();
    const res = runCli(["--root", MINI, "--out", out]);
    expect(res.status, res.stderr).toBe(0);
    const written = readFileSync(join(out, "CONCEPT_MAP.md"));
    expect(written.equals(Buffer.from(renderConceptMap(loadResearchBundle(MINI)), "utf8"))).toBe(
      true,
    );
  });

  it("exits 1 when --root has no concept-map.json", () => {
    const res = runCli(["--root", join(MINI, "does-not-exist"), "--check"]);
    expect(res.status).toBe(1);
    expect(res.stderr).toContain("no research inputs under");
  });
});
