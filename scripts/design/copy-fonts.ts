// Font copy CLI: self-hosts the direction fonts and records their licences.
//   node scripts/design/copy-fonts.ts [--check] [--prune] [--root <dir>] [--packages <dir>] [--family <id>]
// Copies every Latin-subset variable WOFF2 file named by a token set's font.*.$extensions.tnk.files
// from the pinned Fontsource packages to public/fonts/<family>/, byte for byte (Mona Sans carries the
// Reserved Font Name "Mona": the files are never modified), and writes public/fonts/LICENSES.md.
//   --check    no writes; exit 1 listing every missing, differing, unreferenced or stale item
//   --prune    delete font files and empty family folders that no token set references
//   --family   copy one family only (not with --check or --prune)
// Exit 0 ok, 1 problems, 2 bad arguments. Paths use node:path (the repo path has spaces).

import {
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  rmdirSync,
  rmSync,
  statSync,
  writeFileSync,
} from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { listTokenInputs, loadTokens } from "./build-tokens.ts";
import { FONT_KEYS } from "./tokens-schema.ts";

const REPO = resolve(dirname(fileURLToPath(import.meta.url)), "..", "..");
const SRC_RE = /^\/fonts\/([a-z0-9-]+)\/([a-z0-9-]+\.woff2)$/;
export const FONT_BUDGET_BYTES = 200 * 1024;
const USAGE =
  "usage: node scripts/design/copy-fonts.ts [--check] [--prune] [--root <dir>] [--packages <dir>] [--family <id>]";

export interface FontRef {
  family: string;
  file: string;
  src: string;
}

export interface InputRefs {
  input: string;
  refs: FontRef[];
}

/** Every font file each token input references, repo-relative input paths. */
export function collectReferences(root: string): InputRefs[] {
  const all = listTokenInputs(root);
  const inputs = [...new Set([all.system.input, ...all.directions.map((d) => d.input)])];
  return inputs.map((input) => {
    const doc = loadTokens(root, input);
    const refs: FontRef[] = [];
    for (const k of FONT_KEYS) {
      for (const f of doc.font[k].$extensions?.tnk.files ?? []) {
        const m = SRC_RE.exec(f.src);
        if (!m) throw new Error(`${input}: font src ${f.src} is not /fonts/<family>/<file>.woff2`);
        if (!refs.some((r) => r.src === f.src)) {
          refs.push({ family: m[1] as string, file: m[2] as string, src: f.src });
        }
      }
    }
    return { input, refs };
  });
}

interface PackageInfo {
  id: string;
  name: string;
  version: string;
  family: string;
  licence: string;
  attribution: string;
  source: string;
  licenceText: string;
}

function readPackage(packagesDir: string, id: string): PackageInfo {
  const dir = join(packagesDir, id);
  const pkg = JSON.parse(readFileSync(join(dir, "package.json"), "utf8")) as {
    name: string;
    version: string;
  };
  const meta = JSON.parse(readFileSync(join(dir, "metadata.json"), "utf8")) as {
    family: string;
    license: { type: string; attribution: string };
    source?: string;
  };
  return {
    id,
    name: pkg.name,
    version: pkg.version,
    family: meta.family,
    licence: meta.license.type,
    attribution: meta.license.attribution,
    source: meta.source ?? "",
    licenceText: readFileSync(join(dir, "LICENSE"), "utf8").replaceAll("\r\n", "\n").trimEnd(),
  };
}

/** The generated LICENSES.md for the given referenced files, families alphabetical. */
export function renderLicences(packagesDir: string, refs: readonly FontRef[]): string {
  const families = [...new Set(refs.map((r) => r.family))].sort();
  const parts = [
    "# Font licences",
    "",
    "Generated by scripts/design/copy-fonts.ts, do not edit. Each file is a straight, unmodified copy of the Latin-subset variable WOFF2 from the pinned Fontsource package named below; no font request leaves localhost.",
  ];
  for (const id of families) {
    const info = readPackage(packagesDir, id);
    const files = refs
      .filter((r) => r.family === id)
      .map((r) => r.src)
      .sort();
    parts.push(
      "",
      `## ${info.family}`,
      "",
      `- Package: ${info.name} ${info.version}`,
      `- Licence: ${info.licence}`,
      `- Copyright: ${info.attribution}`,
      ...(info.source ? [`- Source: ${info.source}`] : []),
      `- Files: ${files.map((f) => `\`${f}\``).join(", ")}`,
      "",
      "```text",
      info.licenceText,
      "```",
    );
  }
  return `${parts.join("\n")}\n`;
}

function listWoff2(dir: string): string[] {
  if (!existsSync(dir)) return [];
  const out: string[] = [];
  for (const name of readdirSync(dir)) {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) {
      for (const f of readdirSync(path)) if (f.endsWith(".woff2")) out.push(`/fonts/${name}/${f}`);
    }
  }
  return out.sort();
}

export interface Plan {
  problems: string[];
  copied: string[];
  pruned: string[];
}

export function run(options: {
  root: string;
  packagesDir: string;
  check: boolean;
  prune: boolean;
  family?: string;
}): Plan {
  const { root, packagesDir, check, prune, family } = options;
  const fontsDir = join(root, "public", "fonts");
  const inputs = collectReferences(root);
  const allRefs: FontRef[] = [];
  for (const i of inputs)
    for (const r of i.refs) if (!allRefs.some((x) => x.src === r.src)) allRefs.push(r);
  const refs = family === undefined ? allRefs : allRefs.filter((r) => r.family === family);
  const plan: Plan = { problems: [], copied: [], pruned: [] };

  for (const r of refs) {
    const from = join(packagesDir, r.family, "files", r.file);
    const to = join(fontsDir, r.family, r.file);
    if (!existsSync(from)) {
      plan.problems.push(`package file missing: ${from}`);
      continue;
    }
    const bytes = readFileSync(from);
    const have = existsSync(to) ? readFileSync(to) : null;
    if (have !== null && Buffer.compare(have, bytes) === 0) continue;
    if (check) {
      plan.problems.push(have === null ? `missing: ${r.src}` : `differs from package: ${r.src}`);
    } else {
      mkdirSync(dirname(to), { recursive: true });
      writeFileSync(to, bytes);
      plan.copied.push(r.src);
    }
  }

  // Budget: every input's own files, at most 200 KB.
  for (const i of inputs) {
    let total = 0;
    for (const r of i.refs) {
      const p = join(packagesDir, r.family, "files", r.file);
      if (existsSync(p)) total += statSync(p).size;
    }
    if (total > FONT_BUDGET_BYTES) {
      plan.problems.push(
        `over budget: ${i.input} references ${total} bytes (limit ${FONT_BUDGET_BYTES})`,
      );
    }
  }

  // Unreferenced files.
  const referenced = new Set(allRefs.map((r) => r.src));
  for (const src of listWoff2(fontsDir)) {
    if (referenced.has(src)) continue;
    if (prune) {
      rmSync(join(root, "public", src));
      plan.pruned.push(src);
    } else if (check) {
      plan.problems.push(`unreferenced: ${src}`);
    }
  }
  if (prune && existsSync(fontsDir)) {
    for (const name of readdirSync(fontsDir)) {
      const dir = join(fontsDir, name);
      if (statSync(dir).isDirectory() && readdirSync(dir).length === 0) rmdirSync(dir);
    }
  }

  // Licences.
  const licencePath = join(fontsDir, "LICENSES.md");
  // Always every referenced family: --family narrows the copy loop only, never the licence record
  // (OFL-1.1 requires the licence to travel with each shipped font).
  const wanted = renderLicences(packagesDir, allRefs);
  const current = existsSync(licencePath) ? readFileSync(licencePath, "utf8") : null;
  if (current !== wanted) {
    if (check) plan.problems.push("stale: public/fonts/LICENSES.md");
    else {
      mkdirSync(fontsDir, { recursive: true });
      writeFileSync(licencePath, wanted);
    }
  }
  return plan;
}

function main(argv: string[]): number {
  let root = REPO;
  let packagesDir: string | undefined;
  let family: string | undefined;
  let check = false;
  let prune = false;
  for (let i = 0; i < argv.length; i += 1) {
    const a = argv[i];
    if (a === "--check") check = true;
    else if (a === "--prune") prune = true;
    else if (a === "--root" || a === "--packages" || a === "--family") {
      const v = argv[i + 1];
      if (v === undefined) {
        console.error(`${a} needs a value\n${USAGE}`);
        return 2;
      }
      if (a === "--root") root = resolve(v);
      else if (a === "--packages") packagesDir = resolve(v);
      else family = v;
      i += 1;
    } else {
      console.error(`unknown option ${a}\n${USAGE}`);
      return 2;
    }
  }
  if (family !== undefined && (check || prune)) {
    console.error(`--family cannot be combined with --check or --prune\n${USAGE}`);
    return 2;
  }
  const packages = packagesDir ?? join(root, "node_modules", "@fontsource-variable");
  let plan: Plan;
  try {
    plan = run({ root, packagesDir: packages, check, prune, family });
  } catch (err) {
    console.error((err as Error).message);
    return 1;
  }
  for (const p of plan.problems) console.error(`fonts: ${p}`);
  if (plan.problems.length > 0) return 1;
  console.log(
    check
      ? "fonts ok"
      : `fonts: ${plan.copied.length} copied, ${plan.pruned.length} pruned, licences written`,
  );
  return 0;
}

if (process.argv[1] !== undefined && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  process.exit(main(process.argv.slice(2)));
}
