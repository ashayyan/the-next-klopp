import { readFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import {
  fromCanonical,
  PROVIDERS,
  type ProviderId,
  providerBounds,
  statsBombCellCentre,
  toCanonical,
} from "./coords.ts";

interface LandmarkCase {
  provider: ProviderId;
  name: string;
  targetPitch: { length: number; width: number };
  sourcePitch?: { length: number; width: number };
  input: [number, number];
  expected: [number, number];
}

const fixture = JSON.parse(
  readFileSync(join(process.cwd(), "src", "pitch", "fixtures", "landmarks.json"), "utf8"),
) as { kloppyVersion: string; cases: LandmarkCase[] };

const TOL = 1e-9;
const STANDARD = { length: 105, width: 68 };
const ALL: ProviderId[] = ["statsbomb", "opta", "wyscout", "tracab", "tracking-metres", "metrica"];

/** Small seeded PRNG (mulberry32) so the random round-trip points are reproducible. */
function mulberry32(seed: number): () => number {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

function canon(provider: ProviderId, x: number, y: number, pitch = STANDARD) {
  return toCanonical(provider, { x, y }, { pitch });
}

describe("provider table", () => {
  it("frames all six provider ids", () => {
    expect(Object.keys(PROVIDERS)).toHaveLength(ALL.length);
    expect(Object.keys(PROVIDERS).sort()).toEqual([...ALL].sort());
    for (const id of ALL) expect(PROVIDERS[id]?.id).toBe(id);
  });
});

describe("landmarks.json (generated by kloppy)", () => {
  it("is pinned to kloppy 3.19.1 and covers every provider", () => {
    expect(fixture.kloppyVersion).toBe("3.19.1");
    expect(new Set(fixture.cases.map((c) => c.provider))).toEqual(new Set(ALL));
  });

  it.each(fixture.cases.map((c) => [`${c.provider}: ${c.name}`, c] as const))(
    "%s matches kloppy within 1e-9",
    (_label, c) => {
      const out = toCanonical(
        c.provider,
        { x: c.input[0], y: c.input[1] },
        { pitch: c.targetPitch, sourcePitch: c.sourcePitch },
      );
      expect(Math.abs(out.x - c.expected[0])).toBeLessThan(TOL);
      expect(Math.abs(out.y - c.expected[1])).toBeLessThan(TOL);
    },
  );
});

describe("the same landmark lands on the same canonical spot", () => {
  it("puts every provider's left penalty spot at (11, 34)", () => {
    const spots: Array<[ProviderId, number, number]> = [
      ["statsbomb", 12, 40],
      ["opta", 11.5, 50],
      ["wyscout", 10, 50],
      ["tracab", -4150, 0],
      ["tracking-metres", -41.5, 0],
      ["metrica", 11 / 105, 0.5],
    ];
    for (const [provider, x, y] of spots) {
      const p = canon(provider, x, y);
      expect(p.x, provider).toBeCloseTo(11, 9);
      expect(p.y, provider).toBeCloseTo(34, 9);
    }
  });

  it("puts the left penalty-area top corner at (16.5, 13.84)", () => {
    for (const [provider, x, y] of [
      ["opta", 17, 78.9],
      ["wyscout", 16, 19],
      ["tracab", -3600, 2016],
    ] as Array<[ProviderId, number, number]>) {
      const p = canon(provider, x, y);
      expect(p.x, provider).toBeCloseTo(16.5, 9);
      expect(p.y, provider).toBeCloseTo(13.84, 9);
    }
  });
});

describe("left/right and top/bottom asymmetry", () => {
  it("keeps StatsBomb points near the left mark on the left", () => {
    const left = canon("statsbomb", 14, 40);
    const right = canon("statsbomb", 106, 40);
    expect(left.x).toBeCloseTo(12.8333, 4);
    expect(right.x).toBeCloseTo(92.1667, 4);
    expect(Math.abs(left.x - 94)).toBeGreaterThan(50);
  });

  it("flips Opta y but not Wyscout y", () => {
    const optaTop = canon("opta", 20, 80);
    const optaBottom = canon("opta", 20, 20);
    expect(optaTop.x).toBeCloseTo(19.7206, 4);
    expect(optaTop.y).toBeCloseTo(13.1185, 4);
    expect(optaBottom.y).toBeCloseTo(54.8815, 4);
    const wyBottom = canon("wyscout", 20, 80);
    const wyTop = canon("wyscout", 20, 20);
    expect(wyBottom.x).toBeCloseTo(22.3888, 4);
    expect(wyBottom.y).toBeCloseTo(53.5489, 4);
    expect(wyTop.y).toBeCloseTo(14.4511, 4);
  });

  it("maps Tracab centimetres from a centred, y-up frame", () => {
    expect(canon("tracab", 0, 0)).toEqual({ x: 52.5, y: 34 });
    const corner = canon("tracab", -5250, -3400);
    expect(corner.x).toBeCloseTo(0, 9);
    expect(corner.y).toBeCloseTo(68, 9);
  });
});

describe("non-standard pitches", () => {
  const fulham = { length: 100, width: 65 };

  it("converts StatsBomb onto Fulham's 100 x 65 m scene", () => {
    const spot = canon("statsbomb", 12, 40, fulham);
    expect(spot.x).toBeCloseTo(11, 9);
    expect(spot.y).toBeCloseTo(32.5, 9);
    const right = canon("statsbomb", 108, 40, fulham);
    expect(right.x).toBeCloseTo(89, 9);
    const corner = canon("statsbomb", 120, 80, fulham);
    expect(corner.x).toBeCloseTo(100, 9);
    expect(corner.y).toBeCloseTo(65, 9);
  });

  it("places 100 x 65 m tracking into a 105 x 68 m scene on the Law 1 landmarks", () => {
    const opts = { pitch: STANDARD, sourcePitch: fulham };
    const spot = toCanonical("tracking-metres", { x: -39, y: 0 }, opts);
    expect(spot.x).toBeCloseTo(11, 9);
    expect(spot.y).toBeCloseTo(34, 9);
    const corner = toCanonical("tracking-metres", { x: -50, y: -32.5 }, opts);
    expect(corner.x).toBeCloseTo(0, 9);
    expect(corner.y).toBeCloseTo(68, 9);
  });
});

describe("run-off falls back to the global per-axis scale", () => {
  it("matches kloppy outside the provider range", () => {
    const sb = canon("statsbomb", -2, -2);
    expect(sb.x).toBeCloseTo(-1.75, 9);
    expect(sb.y).toBeCloseTo(-1.7, 9);
    const opta = canon("opta", -2, -2);
    expect(opta.x).toBeCloseTo(-2.1, 9);
    expect(opta.y).toBeCloseTo(69.36, 9);
    const wy = canon("wyscout", 102, 102);
    expect(wy.x).toBeCloseTo(107.1, 9);
    expect(wy.y).toBeCloseTo(69.36, 9);
  });
});

describe("round trip", () => {
  for (const provider of ALL) {
    it(`returns 2000 seeded in-pitch points within 1e-9 (${provider})`, () => {
      const rand = mulberry32(1852 + provider.length);
      const opts =
        provider === "tracking-metres"
          ? { pitch: STANDARD, sourcePitch: { length: 100, width: 65 } }
          : { pitch: STANDARD };
      const b = providerBounds(provider, opts);
      let worst = 0;
      for (let i = 0; i < 2000; i++) {
        const p = {
          x: b.xMin + rand() * (b.xMax - b.xMin),
          y: b.yMin + rand() * (b.yMax - b.yMin),
        };
        const back = fromCanonical(provider, toCanonical(provider, p, opts), opts);
        worst = Math.max(worst, Math.abs(back.x - p.x), Math.abs(back.y - p.y));
      }
      expect(worst).toBeLessThan(TOL);
    });
  }

  it("inverts run-off points too", () => {
    for (const provider of ["statsbomb", "opta", "wyscout"] as ProviderId[]) {
      for (const p of [
        { x: -2, y: -2 },
        { x: 102, y: 81 },
      ]) {
        const back = fromCanonical(provider, toCanonical(provider, p, { pitch: STANDARD }), {
          pitch: STANDARD,
        });
        expect(Math.abs(back.x - p.x)).toBeLessThan(TOL);
        expect(Math.abs(back.y - p.y)).toBeLessThan(TOL);
      }
    }
  });
});

describe("helpers", () => {
  it("statsBombCellCentre subtracts half a cell", () => {
    expect(statsBombCellCentre({ x: 1, y: 1 }, 1)).toEqual({ x: 0.5, y: 0.5 });
    const fine = statsBombCellCentre({ x: 0.1, y: 0.1 }, 2);
    expect(fine.x).toBeCloseTo(0.05, 12);
    expect(fine.y).toBeCloseTo(0.05, 12);
  });

  it("providerBounds reports the in-pitch range", () => {
    expect(providerBounds("statsbomb", { pitch: STANDARD })).toEqual({
      xMin: 0,
      xMax: 120,
      yMin: 0,
      yMax: 80,
    });
    expect(providerBounds("opta", { pitch: STANDARD })).toEqual({
      xMin: 0,
      xMax: 100,
      yMin: 0,
      yMax: 100,
    });
    expect(providerBounds("tracab", { pitch: STANDARD })).toEqual({
      xMin: -5250,
      xMax: 5250,
      yMin: -3400,
      yMax: 3400,
    });
    expect(providerBounds("tracking-metres", { pitch: { length: 100, width: 65 } })).toEqual({
      xMin: -50,
      xMax: 50,
      yMin: -32.5,
      yMax: 32.5,
    });
    expect(providerBounds("metrica", { pitch: STANDARD })).toEqual({
      xMin: 0,
      xMax: 1,
      yMin: 0,
      yMax: 1,
    });
  });

  it("rejects an unknown provider", () => {
    expect(() => canon("nope" as ProviderId, 0, 0)).toThrow(/unknown provider/);
  });
});
